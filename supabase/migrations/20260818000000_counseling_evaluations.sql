-- Reused by every student-facing policy below: the linked counseling request is
-- the student's own AND the session is Completed AND the global form is active.
CREATE OR REPLACE FUNCTION public.student_may_evaluate_counseling(p_request_id bigint) RETURNS boolean
    LANGUAGE sql
    STABLE
    SECURITY DEFINER
    SET search_path = 'public'
    AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.counseling_requests r
        JOIN public.counseling_evaluation_forms f ON f.is_global
        WHERE r.id = p_request_id
          AND r.student_id = public.current_student_id()
          AND r.status = 'Completed'
          AND f.is_active
    );
$$;

REVOKE EXECUTE ON FUNCTION public.student_may_evaluate_counseling(bigint) FROM anon;

-- A student may see the active global form only once they have a completed
-- session of their own. Templates / per-request forms are structurally invisible
-- to students -- no policy can return one.
CREATE OR REPLACE FUNCTION public.student_has_completed_counseling() RETURNS boolean
    LANGUAGE sql
    STABLE
    SECURITY DEFINER
    SET search_path = 'public'
    AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.counseling_requests r
        WHERE r.student_id = public.current_student_id()
          AND r.status = 'Completed'
    );
$$;

REVOKE EXECUTE ON FUNCTION public.student_has_completed_counseling() FROM anon;

