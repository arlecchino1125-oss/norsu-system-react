-- Counseling session + open evaluations.
--
-- Mirrors the event_evaluation_* design on purpose: staff build one evaluation
-- form (scale / text / choice questions) and students answer it once per
-- completed counseling session. The same form also backs "open evaluations" --
-- students who were counseled outside the digital workflow record their session
-- themselves on the public portal, identified by Student ID alone, exactly like
-- the public events portal.
--
-- Layout:
--   * counseling_evaluation_forms   -- ONE global form (is_global = true,
--                                      counseling_request_id = NULL) plus
--                                      optional reusable templates.
--   * counseling_evaluation_questions
--   * counseling_evaluation_responses  -- counseling_request_id NULL marks an
--                                        "open evaluation" recorded outside the
--                                        system counseling flow.
--   * counseling_evaluation_answers
--
-- Coexists with counseling_requests.feedback (the free-text general feedback);
-- it does not replace it.

CREATE TABLE IF NOT EXISTS public.counseling_evaluation_forms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    counseling_request_id bigint REFERENCES public.counseling_requests(id) ON DELETE CASCADE,
    title text NOT NULL,
    description text,
    is_active boolean NOT NULL DEFAULT true,
    is_global boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT counseling_evaluation_forms_title_len CHECK (char_length(title) BETWEEN 1 AND 200),
    CONSTRAINT counseling_evaluation_forms_description_len CHECK (description IS NULL OR char_length(description) <= 1000)
);

-- Exactly one global form. A row with is_global = true always has
-- counseling_request_id NULL (a request-linked form is per-request, not global).
CREATE UNIQUE INDEX IF NOT EXISTS counseling_evaluation_forms_one_global
    ON public.counseling_evaluation_forms (is_global)
    WHERE is_global = true;

-- One evaluation per counseling request (reserved for future per-request forms).
CREATE UNIQUE INDEX IF NOT EXISTS counseling_evaluation_forms_one_per_request
    ON public.counseling_evaluation_forms (counseling_request_id)
    WHERE counseling_request_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.counseling_evaluation_questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id bigint NOT NULL REFERENCES public.counseling_evaluation_forms(id) ON DELETE CASCADE,
    order_index integer NOT NULL DEFAULT 0,
    question_text text NOT NULL,
    question_type text NOT NULL,
    scale_min integer,
    scale_max integer,
    scale_min_label text,
    scale_max_label text,
    choices text[] NOT NULL DEFAULT '{}'::text[],
    is_required boolean NOT NULL DEFAULT true,
    CONSTRAINT counseling_evaluation_questions_text_len CHECK (char_length(question_text) BETWEEN 1 AND 500),
    CONSTRAINT counseling_evaluation_questions_type_chk CHECK (question_type = ANY (ARRAY['scale'::text, 'text'::text, 'choice'::text])),
    -- Each type carries its own required settings, enforced here so a half-built
    -- question cannot reach a student's screen and render blank.
    CONSTRAINT counseling_evaluation_questions_shape_chk CHECK (
        CASE question_type
            WHEN 'choice' THEN coalesce(array_length(choices, 1), 0) >= 2
            WHEN 'scale' THEN scale_min IS NOT NULL AND scale_max IS NOT NULL AND scale_max > scale_min
            ELSE true
        END
    )
);

CREATE INDEX IF NOT EXISTS counseling_evaluation_questions_form_id_idx
    ON public.counseling_evaluation_questions (form_id, order_index);


-- Identity columns are a snapshot, not a join: a student's course and year
-- change between school years, and an evaluation must keep reading the way it
-- read on the day it was submitted. Stamped by trigger, never by the client.
-- counseling_request_id IS NULL means the response is an open evaluation --
-- recorded for a session that did not go through the system counseling flow.
CREATE TABLE IF NOT EXISTS public.counseling_evaluation_responses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id bigint NOT NULL REFERENCES public.counseling_evaluation_forms(id) ON DELETE CASCADE,
    counseling_request_id bigint REFERENCES public.counseling_requests(id) ON DELETE CASCADE,
    student_id character varying NOT NULL REFERENCES public.students(student_id) ON UPDATE CASCADE,
    student_name text,
    department text,
    course text,
    year_level text,
    submitted_at timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now())
);

-- One evaluation per system session. Open evaluations have no unique guard on
-- purpose: a student may record several outside-system sessions over time.
CREATE UNIQUE INDEX IF NOT EXISTS counseling_evaluation_responses_one_per_request
    ON public.counseling_evaluation_responses (counseling_request_id)
    WHERE counseling_request_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS counseling_evaluation_responses_form_id_idx
    ON public.counseling_evaluation_responses (form_id);

CREATE INDEX IF NOT EXISTS counseling_evaluation_responses_student_id_idx
    ON public.counseling_evaluation_responses (student_id);

CREATE TABLE IF NOT EXISTS public.counseling_evaluation_answers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id bigint NOT NULL REFERENCES public.counseling_evaluation_responses(id) ON DELETE CASCADE,
    question_id bigint NOT NULL REFERENCES public.counseling_evaluation_questions(id) ON DELETE CASCADE,
    answer_value integer,
    answer_text text,
    CONSTRAINT counseling_evaluation_answers_one_per_question UNIQUE (response_id, question_id),
    CONSTRAINT counseling_evaluation_answers_text_len CHECK (answer_text IS NULL OR char_length(answer_text) <= 1500)
);

CREATE INDEX IF NOT EXISTS counseling_evaluation_answers_response_id_idx
    ON public.counseling_evaluation_answers (response_id);

-- The student controls the request body, not just the row, so RLS alone cannot
-- stop them posting someone else's name or a flattering department. Stamp all
-- identity fields server-side. For students the snapshot comes from the session;
-- for staff/RPC writes (open evaluations, public portal) it is resolved from the
-- supplied student_id so the identity is still trustworthy.
CREATE OR REPLACE FUNCTION public.stamp_counseling_evaluation_response_identity() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path = 'public'
    AS $$
DECLARE
    v_student public.students;
    v_student_id text := public.current_student_id();
BEGIN
    -- Non-students (Care Staff, Admin, RPCs, service role) supply the student_id.
    IF v_student_id IS NULL THEN
        v_student_id := NEW.student_id;
    END IF;

    SELECT *
    INTO v_student
    FROM public.students s
    WHERE s.student_id = v_student_id;

    IF v_student.student_id IS NOT NULL THEN
        NEW.student_id := v_student.student_id;
        NEW.student_name := trim(concat_ws(' ', v_student.first_name, v_student.middle_name, v_student.last_name, v_student.suffix));
        NEW.department := v_student.department;
        NEW.course := v_student.course;
        NEW.year_level := v_student.year_level;
    END IF;

    NEW.submitted_at := now();
    RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.stamp_counseling_evaluation_response_identity() FROM anon;

DROP TRIGGER IF EXISTS counseling_evaluation_responses_stamp_identity ON public.counseling_evaluation_responses;
CREATE TRIGGER counseling_evaluation_responses_stamp_identity
    BEFORE INSERT ON public.counseling_evaluation_responses
    FOR EACH ROW
    EXECUTE FUNCTION public.stamp_counseling_evaluation_response_identity();

