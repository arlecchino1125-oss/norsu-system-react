-- -----------------------------------------------------------------------------
-- RPC: Save or update a Web Push subscription from the Public Hub
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.public_save_push_subscription(
    p_endpoint text,
    p_p256dh text,
    p_auth text,
    p_student_id text DEFAULT NULL,
    p_user_agent text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_endpoint text := trim(coalesce(p_endpoint, ''));
    v_p256dh text := trim(coalesce(p_p256dh, ''));
    v_auth text := trim(coalesce(p_auth, ''));
    v_student_id text := nullif(trim(coalesce(p_student_id, '')), '');
    v_user_agent text := left(trim(coalesce(p_user_agent, '')), 500);
BEGIN
    IF v_endpoint = '' OR v_p256dh = '' OR v_auth = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Invalid push subscription details.');
    END IF;

    IF v_endpoint NOT LIKE 'https://%' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Push subscription endpoint must use HTTPS.');
    END IF;

    INSERT INTO public.push_subscriptions (
        endpoint,
        p256dh,
        auth,
        student_id,
        user_agent,
        is_active,
        updated_at
    )
    VALUES (
        v_endpoint,
        v_p256dh,
        v_auth,
        v_student_id,
        v_user_agent,
        true,
        now()
    )
    ON CONFLICT (endpoint) DO UPDATE
    SET
        p256dh = EXCLUDED.p256dh,
        auth = EXCLUDED.auth,
        student_id = COALESCE(EXCLUDED.student_id, public.push_subscriptions.student_id),
        user_agent = COALESCE(NULLIF(EXCLUDED.user_agent, ''), public.push_subscriptions.user_agent),
        is_active = true,
        updated_at = now();

    RETURN jsonb_build_object('success', true);
END;
$$;

GRANT EXECUTE ON FUNCTION public.public_save_push_subscription(text, text, text, text, text) TO anon, authenticated;

-- -----------------------------------------------------------------------------
-- RPC: Remove a Web Push subscription from the Public Hub
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.public_remove_push_subscription(
    p_endpoint text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_endpoint text := trim(coalesce(p_endpoint, ''));
BEGIN
    IF v_endpoint = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Endpoint is required.');
    END IF;

    DELETE FROM public.push_subscriptions
    WHERE endpoint = v_endpoint;

    RETURN jsonb_build_object('success', true);
END;
$$;

GRANT EXECUTE ON FUNCTION public.public_remove_push_subscription(text) TO anon, authenticated;

-- -----------------------------------------------------------------------------
-- RPC: Fetch recent push broadcasts (used for missed alerts when opening app)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.public_get_recent_push_notifications(
    p_since timestamptz DEFAULT NULL
)
RETURNS SETOF public.public_push_notifications
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT *
    FROM public.public_push_notifications
    WHERE created_at > COALESCE(p_since, now() - interval '24 hours')
    ORDER BY created_at DESC
    LIMIT 5;
$$;

GRANT EXECUTE ON FUNCTION public.public_get_recent_push_notifications(timestamptz) TO anon, authenticated;

