-- =============================================================================
-- Public Portal PWA Web Push Subscriptions & Broadcast Notifications
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    endpoint text NOT NULL UNIQUE,
    p256dh text NOT NULL,
    auth text NOT NULL,
    student_id text NULL,
    user_agent text NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_push_subscriptions_active
    ON public.push_subscriptions (is_active, updated_at DESC);

ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

-- Subscriptions are managed through SECURITY DEFINER RPCs and Edge Functions
REVOKE ALL ON TABLE public.push_subscriptions FROM anon, authenticated;

CREATE TABLE IF NOT EXISTS public.public_push_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category text NOT NULL DEFAULT 'Announcement',
    title text NOT NULL,
    body text NOT NULL,
    url text NOT NULL DEFAULT '/public',
    tag text NOT NULL,
    created_by text NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_public_push_notifications_created_at
    ON public.public_push_notifications (created_at DESC);

ALTER TABLE public.public_push_notifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read push broadcasts" ON public.public_push_notifications;
CREATE POLICY "Public can read push broadcasts"
    ON public.public_push_notifications
    FOR SELECT
    TO anon, authenticated
    USING (true);

REVOKE INSERT, UPDATE, DELETE ON TABLE public.public_push_notifications FROM anon, authenticated;
GRANT SELECT ON TABLE public.public_push_notifications TO anon, authenticated;

